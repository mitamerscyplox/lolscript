/**
 * Saves the LoL products of the Shopier store to api/_lib/shopier-listings.mjs.
 * Shopier blocks Vercel's servers, so the site falls back to this list there.
 * Run from a normal connection after changing Shopier products: node scripts/shopier-snapshot.mjs
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const envFile = fileURLToPath(new URL("../.env", import.meta.url));
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*(SHOPIER_[A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
  }
}

const { listShopierProducts } = await import("../api/_lib/shopier.mjs");
const { LOL_TITLE_RE } = await import("../api/_lib/shopier-catalog.mjs");
const { products, error } = await listShopierProducts();
if (error) throw new Error(error);
const visible = products
  .filter((p) => LOL_TITLE_RE.test(String(p.title || "")))
  .map((p) => ({ id: String(p.id), title: String(p.title), url: String(p.url), priceData: p.priceData, stockStatus: p.stockStatus || "inStock" }));

// Hidden listings are not in the store listing; keep the saved ones whose page still exists
// (a deleted product redirects to the store page).
const { default: saved } = await import("../api/_lib/shopier-listings.mjs");
const visibleIds = new Set(visible.map((p) => p.id));
const hidden = [];
for (const p of saved.filter((s) => s.hidden && !visibleIds.has(s.id))) {
  const res = await fetch(`https://www.shopier.com/${p.id}`, { redirect: "manual", headers: { "User-Agent": "Mozilla/5.0" } });
  if (res.status === 200) hidden.push(p);
  else console.log(`dropped deleted hidden listing "${p.title}" (${p.id})`);
}
const lol = [...visible, ...hidden];
if (!lol.length) throw new Error("No LoL products found on Shopier");

const out = fileURLToPath(new URL("../api/_lib/shopier-listings.mjs", import.meta.url));
writeFileSync(
  out,
  `/** Generated by scripts/shopier-snapshot.mjs on ${new Date().toISOString().slice(0, 10)}. */\nexport default ${JSON.stringify(lol, null, 2)};\n`
);
console.log(`Saved ${lol.length} Shopier products (${hidden.length} hidden)`);
